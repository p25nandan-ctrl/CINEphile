import json,glob,os,re
out=[]
files=sorted(glob.glob('/home/claude/content/stories/*.json'))
MOT=['sun','moon','wave','hills','flower','fort']
ART='Pictures: none yet. Each page shows a “picture to come” panel, and illustration prompts are prepared for an artist. No picture has been made or generated for this story.'
HIART='चित्र: अभी नहीं बने हैं।'
stories=[]
for f in files:
    d=json.load(open(f,encoding='utf8'))
    o=str(d['origLevel']);L=d['levels'][o]
    src=[]
    for s in d['sources']:
        x={'l':s['l'],'v':s['v'],'s':'ok'}
        for k in('url','n'):
            if s.get(k): x[k]=s[k]
        src.append(x)
    r={'id':d['id'],'state':d['state'],'title':d['title'],'titleHi':d['titleHi'],'genre':d['genre'],'lv':d['origLevel'],
       'levelNote':'The supplied version is closest to this level: '+d['levelReason'],
       'texts':L['texts'],'vocab':L['vocab'],'questions':L['questions'],'levels':d['levels'],
       'imagine':d['imagine'],'create':d['create'],'scenes':d['scenes'],'pages':{'en':d['pages'],'hi':d['pages']},
       'artCredit':ART,'placeholderArt':True,'artStyle':d.get('artStyle'),'about':d['about'],'sources':src}
    stories.append((r,d))
js=['/* generated by /home/claude/content/gen_stories.py from content/stories/*.json: do not edit by hand */','(function(){','const GEN=%s;'%json.dumps([r for r,_ in stories],ensure_ascii=False),
'const META=%s;'%json.dumps({d['id']:{'summary':d['summary'],'from':d['from']} for _,d in stories},ensure_ascii=False),
'const MOT=%s;'%json.dumps(MOT),
'GEN.forEach((r,n)=>{REAL[r.id]=r;const st=STATES[r.state];if(!st)return;const m=META[r.id];',
' const ex=st.books.find(b=>b.t===r.title);',
' const book={t:r.title,sub:r.titleHi,lv:r.lv,th:st.ico||"📖",m:MOT[n%MOT.length],d:m.summary,from:m.from,story:r.id,texts:r.texts};',
' if(ex){Object.assign(ex,{story:r.id,texts:r.texts,lv:r.lv});if(!ex.sub)ex.sub=r.titleHi;r.ico=st.ico}else{st.books.unshift(book);r.ico=st.ico}});',
'})();']
open('/home/claude/site/stories_gen.js','w',encoding='utf8').write('\n'.join(js))
print(len(stories),'stories')
